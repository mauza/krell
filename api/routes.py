@router.post("/admin/reload-plugins")
async def reload_plugins():
    """
    Manually trigger a reload of all plugins.

    This endpoint allows manual plugin reloading without restarting the server.
    Useful for development and when auto-reload is disabled.
    """
    try:
        from main import plugin_loader

        plugin_loader.reload_plugins()

        tools = plugin_loader.get_tools()
        metadata = plugin_loader.get_plugin_metadata()

        return {
            "success": True,
            "message": "Plugins reloaded successfully",
            "tools_count": len(tools),
            "plugins_loaded": len([m for m in metadata if m["status"] == "loaded"]),
            "plugins_failed": len([m for m in metadata if m["status"] == "error"]),
            "plugins": metadata,
        }
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))


