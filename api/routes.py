async def get_krell_agent():
    """Get or create KrellAgent instance with current settings."""
    global _krell_agent

    # Return cached agent if available
    if _krell_agent is not None:
        return _krell_agent

    async with _krell_agent_lock:
        # Double-check after acquiring lock
        if _krell_agent is not None:
            return _krell_agent

        # Create new agent instance
        from core.agent import KrellAgent
        from main import db as legacy_db

        database = Database(legacy_db.db_path)
        agent = await KrellAgent.create(database)

        from main import plugin_loader

        tools = plugin_loader.get_tools()

        if hasattr(agent, "_strands_agent") and tools:
            agent._strands_agent.tools = tools

        _krell_agent = agent
        return _krell_agent


async def reload_krell_agent():
    """Force reload of KrellAgent instance with current settings."""
    global _krell_agent

    async with _krell_agent_lock:
        # Clear cached agent
        _krell_agent = None

        # Create new agent instance
        _krell_agent = await get_krell_agent()

    return _krell_agent


