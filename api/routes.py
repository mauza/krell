@router.post("/tts/stream")
async def tts_stream(request: TTSRequest):
    """Stream TTS audio generated by Kyutai via chunked transfer."""
    try:
        voice = request.voice or config.tts_voice
        fmt = request.format or config.tts_format
        media_type = "audio/wav" if fmt == "wav" else "audio/mpeg"
        max_text_length = config.tts_max_text_length

        async def generator():
            # Use Kyutai direct in-process inference with chunking
            async for chunk in tts_service.stream_tts_chunked(
                request.text,
                max_text_length=max_text_length,
                voice=voice,
                lang=config.tts_lang,
                speed=config.tts_speed,
            ):
                yield chunk

        headers = {
            "Content-Disposition": "inline; filename=tts.%s"
            % ("wav" if fmt == "wav" else "mp3"),
            "Accept-Ranges": "bytes",
            "Cache-Control": "no-cache",
        }
        return StreamingResponse(generator(), media_type=media_type, headers=headers)
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))


