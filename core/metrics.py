"""
Prometheus Metrics - Production-grade observability for Krell.

This module provides Prometheus metrics for monitoring:
- LLM request latency and throughput
- TTS synthesis latency and throughput
- WebSocket connections
- Tool/plugin usage
- Error rates

Usage:
    from core.metrics import (
        LLM_REQUESTS,
        LLM_REQUEST_DURATION,
        record_llm_request,
    )

    # Using context manager for timing
    with LLM_REQUEST_DURATION.labels(model="gpt-4").time():
        response = await llm.generate(...)

    # Or manually
    start = time.time()
    response = await llm.generate(...)
    LLM_REQUEST_DURATION.labels(model="gpt-4").observe(time.time() - start)
    LLM_REQUESTS.labels(model="gpt-4", status="success").inc()

The /metrics endpoint exposes all metrics in Prometheus format.
"""

