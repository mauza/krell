def set_app_info(version: str, **labels: str) -> None:
    """Set application info labels."""
    APP_INFO.info({"version": version, **labels})


@contextmanager
def track_llm_request(model: str):
    """
    Context manager to track LLM request metrics.

    Usage:
        with track_llm_request("gpt-4") as tracker:
            response = await llm.generate(...)
            tracker.record_tokens(input=100, output=50)
    """
    start_time = time.time()
    tracker = _LLMTracker(model, start_time)
    try:
        yield tracker
        LLM_REQUESTS.labels(model=model, status="success").inc()
    except Exception as e:
        LLM_REQUESTS.labels(model=model, status="error").inc()
        error_type = type(e).__name__
        LLM_ERRORS.labels(model=model, error_type=error_type).inc()
        raise
    finally:
        duration = time.time() - start_time
        LLM_REQUEST_DURATION.labels(model=model).observe(duration)


class _LLMTracker:
    """Helper class for tracking LLM metrics within a request."""

    def __init__(self, model: str, start_time: float):
        self.model = model
        self.start_time = start_time
        self._first_token_recorded = False

    def record_first_token(self) -> None:
        """Record time to first token."""
        if not self._first_token_recorded:
            ttft = time.time() - self.start_time
            LLM_TTFT.labels(model=self.model).observe(ttft)
            self._first_token_recorded = True

    def record_tokens(self, input_tokens: int = 0, output_tokens: int = 0) -> None:
        """Record token counts."""
        if input_tokens > 0:
            LLM_TOKENS_INPUT.labels(model=self.model).observe(input_tokens)
        if output_tokens > 0:
            LLM_TOKENS_OUTPUT.labels(model=self.model).observe(output_tokens)
            LLM_TOKENS_GENERATED.labels(model=self.model).inc(output_tokens)


@contextmanager
def track_tts_request(provider: str, voice: str):
    """
    Context manager to track TTS request metrics.

    Usage:
        with track_tts_request("kyutai", "default") as tracker:
            audio = await tts.synthesize(text)
            tracker.record_audio_duration(2.5)
    """
    start_time = time.time()
    tracker = _TTSTracker(provider, voice)
    try:
        yield tracker
        TTS_REQUESTS.labels(provider=provider, voice=voice, status="success").inc()
    except Exception as e:
        TTS_REQUESTS.labels(provider=provider, voice=voice, status="error").inc()
        error_type = type(e).__name__
        TTS_ERRORS.labels(provider=provider, error_type=error_type).inc()
        raise
    finally:
        duration = time.time() - start_time
        TTS_REQUEST_DURATION.labels(provider=provider, voice=voice).observe(duration)


class _TTSTracker:
    """Helper class for tracking TTS metrics within a request."""

    def __init__(self, provider: str, voice: str):
        self.provider = provider
        self.voice = voice

    def record_audio_duration(self, duration: float) -> None:
        """Record the duration of generated audio."""
        TTS_AUDIO_DURATION.labels(provider=self.provider, voice=self.voice).observe(duration)

    def record_characters(self, count: int) -> None:
        """Record characters processed."""
        TTS_CHARACTERS_PROCESSED.labels(provider=self.provider).inc(count)


@contextmanager
def track_tool_call(tool_name: str):
    """
    Context manager to track tool call metrics.

    Usage:
        with track_tool_call("weather_tool"):
            result = await weather_tool.execute(location="NYC")
    """
    start_time = time.time()
    try:
        yield
        TOOL_CALLS.labels(tool_name=tool_name, status="success").inc()
    except Exception as e:
        TOOL_CALLS.labels(tool_name=tool_name, status="error").inc()
        error_type = type(e).__name__
        TOOL_ERRORS.labels(tool_name=tool_name, error_type=error_type).inc()
        raise
    finally:
        duration = time.time() - start_time
        TOOL_DURATION.labels(tool_name=tool_name).observe(duration)


def record_error(error_type: str, component: str) -> None:
    """Record an error occurrence."""
    ERRORS_TOTAL.labels(error_type=error_type, component=component).inc()


def get_metrics() -> bytes:
    """
    Generate Prometheus metrics in exposition format.

    Returns:
        Metrics data as bytes for the /metrics endpoint
    """
    return generate_latest()


def get_metrics_content_type() -> str:
    """Get the content type for metrics endpoint."""
    return CONTENT_TYPE_LATEST
